import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { apply } from '../src/index.mjs';

test('media API stores one job, serves validated generated bytes with Range and keeps project/session boundaries', async t => {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), 'wtt-media-api-')));
  const other = realpathSync(mkdtempSync(path.join(tmpdir(), 'wtt-media-api-other-')));
  const disposers = [], tools = new Map();
  let endpoint, submissions = 0;
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64');
  const caps = { endpoint: 'http://127.0.0.1:8000', healthy: true, credentialConfigured: true,
    modelDefaults: { image: { model: 'jimeng-5.0', ratio: '4:3', resolution: '2k' }, video: { model: 'jimeng-video-3.0', ratio: '4:3', resolution: '720p', duration: 5 } },
    models: [{ id: 'jimeng-5.0', type: 'image', requiresReference: false, maxReferences: 10, ratios: ['4:3'], resolutions: ['2k'] }] };
  const provider = { capabilities: async () => caps, updateSettings: async () => caps,
    submit: async () => { submissions++; return { resultBase64: image.toString('base64') }; }, close() {} };
  apply({ effect(fn) { const dispose = fn(); if (typeof dispose === 'function') disposers.push(dispose); },
    connection: { fetch: { register(entry) { endpoint = entry; return () => {}; } } },
    tools: { register(tool) { tools.set(tool.name, tool); return () => {}; } }, skills: { register() { return () => {}; } },
  }, { workspaceRoot: root, registryFile: path.join(root, 'projects.json'), mediaProvider: provider });
  t.after(() => { for (const dispose of disposers.reverse()) dispose(); rmSync(root, { recursive: true, force: true }); rmSync(other, { recursive: true, force: true }); });
  const request = (query = {}, action, data, headers) => endpoint.fetch(new Request(`http://localhost/api/wtt-creation-workbench?${new URLSearchParams(query)}`, action ? { method: 'POST', body: JSON.stringify({ action, data }) } : { headers }));
  const call = async (query, action, data) => { const response = await request(query, action, data); const result = await response.json(); assert.equal(response.status, 200, result.error); return result; };
  const state = await call({});
  const projectId = state.projectId;
  assert.deepEqual(await call({ projectId, mediaCapabilities: '1' }), caps);
  assert.deepEqual((await call({ projectId, mediaApiCapabilities: '1' })).providers, []);
  const missingApi = await request({ projectId }, 'generate-media-api', { outputType: 'image', generationMethod: 'api', providerId: 'missing', instruction: '合成请求' });
  assert.equal(missingApi.status, 400);
  assert.match((await missingApi.json()).error, /尚未接入/);
  assert.equal(submissions, 0, 'API 缺接入时不能回退到旧即梦');
  const requirement = await call({ projectId }, 'create', { title: '媒体API合成验收，不调用真实模型', operationId: randomUUID() });
  const board = await call({ projectId, canvas: requirement.id });
  const anchor = board.nodes.find(node => node.kind === 'requirement');
  const data = { requirementId: requirement.id, instruction: '合成协议测试 /literal-token', outputType: 'image',
    selectedCardIds: [anchor.id], sourceRefs: [{ cardId: anchor.id, hash: anchor.sourceHash }], media: caps.modelDefaults.image, operationId: randomUUID() };
  const result = await call({ projectId }, 'generate-media', data);
  assert.equal(result.task.kind, 'media'); assert.equal(result.task.sessionId, null);
  const replay = await call({ projectId }, 'generate-media', data); assert.equal(replay.task.id, result.task.id);
  let job;
  for (let i = 0; i < 150; i++) {
    job = (await call({ projectId, mediaJob: result.task.id })).job;
    if (['succeeded', 'failed', 'unknown', 'registration_failed', 'download_failed'].includes(job.status)) break;
    await delay(10);
  }
  assert.equal(job.status, 'succeeded', job.error); assert.equal(submissions, 1);
  const detail = await call({ projectId, task: result.task.id });
  assert.equal(detail.status, 'output'); assert.equal(detail.mediaJob.artifactId, job.artifactId);
  assert.deepEqual(detail.input.media, caps.modelDefaults.image); assert.match(detail.input.effectivePrompt, /literal-token/);
  const output = (await call({ projectId, canvas: requirement.id })).nodes.find(node => node.refId === job.artifactId);
  assert.equal(output.kind, 'artifact'); assert.equal(output.generatedFile.mime, 'image/png');
  const downloaded = await request({ projectId, downloadArtifact: job.artifactId });
  assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()), image);
  const partial = await request({ projectId, downloadArtifact: job.artifactId, preview: '1' }, undefined, undefined, { range: 'bytes=0-7' });
  assert.equal(partial.status, 206); assert.deepEqual(Buffer.from(await partial.arrayBuffer()), image.subarray(0, 8));
  const projectB = (await call({}, 'open-project', { path: other })).project;
  assert.equal((await request({ projectId: projectB.id, mediaJob: result.task.id })).status, 400);
  assert.equal((await request({ projectId: projectB.id, downloadArtifact: job.artifactId })).status, 400);
  const register = tools.get('course_register_artifact');
  await assert.rejects(register.execute({ projectId, taskId: result.task.id, kind: 'image', title: '禁止越权', path: detail.files[0].path, operationId: randomUUID() },
    { signal: new AbortController().signal, agent: { id: 'unbound-session', session: { header: { cwd: root } } } }), /会话|媒体|类型|登记|必须属于已有 AI 创作任务/);
});
